// DOM элементы
const audioPlayer = document.getElementById('audioPlayer');
const volumeSlider = document.getElementById('volumeSlider');
const trackTitle = document.getElementById('trackTitle');
const trackAlbum = document.getElementById('trackAlbum');
const currentTimeEl = document.getElementById('currentTime');
const durationEl = document.getElementById('duration');
const slideImage = document.getElementById('slideImage');
const slidePlaceholder = document.getElementById('slidePlaceholder');
const vinyl = document.getElementById('vinyl');
const playBtn = document.getElementById('playBtn');

// Переменные состояния
let currentTrackIndex = 0;
let isPlaying = false;

// Инициализация
function init() {
    const randomIndex = Math.floor(Math.random() * playlist.length);
    loadTrack(randomIndex);
    audioPlayer.volume = 0.7;
    audioPlayer.addEventListener('ended', nextTrack);
    playBtn.addEventListener('click', togglePlay);
}

// Загрузка трека
function loadTrack(index) {
    currentTrackIndex = index;
    const track = playlist[index];
    audioPlayer.src = track.url;
    trackTitle.textContent = track.title;
    trackAlbum.textContent = track.album;
    
    // Загрузка изображения альбома
    slideImage.src = track.albumImage;
    slideImage.onload = () => {
        slidePlaceholder.style.display = 'none';
        slideImage.style.display = 'block';
    };
    slideImage.onerror = () => {
        slidePlaceholder.style.display = 'flex';
        slideImage.style.display = 'none';
    };
}

// Следующий трек (рандомный)
function nextTrack() {
    const randomIndex = Math.floor(Math.random() * playlist.length);
    loadTrack(randomIndex);
    if (isPlaying) {
        audioPlayer.play();
    }
}

// Обновление таймкода
audioPlayer.addEventListener('timeupdate', () => {
    if (audioPlayer.duration) {
        currentTimeEl.textContent = formatTime(audioPlayer.currentTime);
        durationEl.textContent = formatTime(audioPlayer.duration);
    }
});

// Громкость
volumeSlider.addEventListener('input', (e) => {
    audioPlayer.volume = e.target.value / 100;
});

// Форматирование времени
function formatTime(seconds) {
    if (isNaN(seconds)) return '0:00';
    const mins = Math.floor(seconds / 60);
    const secs = Math.floor(seconds % 60);
    return `${mins}:${secs.toString().padStart(2, '0')}`;
}

// Обработчик кнопки play/pause
function togglePlay() {
    if (isPlaying) {
        audioPlayer.pause();
        playBtn.textContent = '▶ Play';
        playBtn.classList.remove('playing');
    } else {
        audioPlayer.play();
        playBtn.textContent = '⏸ Stop';
        playBtn.classList.add('playing');
    }
    isPlaying = !isPlaying;
}

// Запуск
init();
